// Snapshot the ALPS visual contract without importing React or changing ALPS.
// node tools/sync-alps-design-system.js [path/to/alps-react-app] [--check]
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const alps = path.resolve(process.argv.find((a, i) => i > 1 && !a.startsWith('--')) || path.join(root, '../alps-react-app'));
const read = file => fs.readFileSync(path.join(alps, file), 'utf8');
const app = read('src/App.css');
const color = name => {
  const match = app.match(new RegExp('--' + name + '\\s*:\\s*([^;]+);'));
  if (!match) throw new Error('ALPS token missing: ' + name);
  return match[1].trim();
};
const extract = (file, names) => {
  const ctx = vm.createContext({});
  vm.runInContext(read(file).replace(/export /g, '') + '\nthis.result={' + names.join(',') + '};', ctx);
  return ctx.result;
};
const { ITEM_TYPE_ICON_PATH, DEFAULT_PATH } = extract('src/screens/Enhancements/ItemGraphViz/item-type-icon-paths.js', ['ITEM_TYPE_ICON_PATH', 'DEFAULT_PATH']);
const { ITEM_TYPE_FILL_COLOR } = extract('src/utils/item-type-icon-style.js', ['ITEM_TYPE_FILL_COLOR']);
const icons = {};
for (const [key, file] of Object.entries({ skill: 'skill_grey', analytics: 'analytics', monitoring: 'monitoring', history: 'history', assignment: 'assignment', book: 'menu_book_thin', grid: 'grid_view', down: 'trending_down', up: 'trending_up', person: 'person' })) {
  const svg = read('src/assets/svg/' + file + '.svg');
  const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map(m => m[1]);
  if (!paths.length) throw new Error('No path in ' + file);
  icons[key] = { viewBox: svg.match(/viewBox="([^"]+)"/)[1], paths };
}
for (const [key, d] of Object.entries({ ...ITEM_TYPE_ICON_PATH, unknown: DEFAULT_PATH })) icons[key] = { viewBox: '0 -960 960 960', paths: [d] };
const labels = { activecode: 'Code', mchoice: 'Multiple choice', fillintheblank: 'Fill in the blank', parsonsprob: 'Parsons problem', hparsons: 'Horizontal Parsons problem', clickablearea: 'Clickable area', dragndrop: 'Drag and drop', shortanswer: 'Short answer', reading: 'Reading', figure: 'Figure', video: 'Video', youtube: 'Video' };
const levels = ['Beginning', 'Attempted', 'Familiar', 'Proficient', 'Mastered'].map((label, i) => ({ label, token: ['not-started', 'attempted', 'familiar', 'proficient', 'mastered'][i] }));
const engagement = ['Not started', 'Low', 'Medium', 'High', 'Very high'].map((label, i) => ({ label, token: ['not-started', 'low-engagement', 'medium-engagement', 'high-engagement', 'very-high-engagement'][i] }));
const tokens = {
  primary: 'primary-blue', 'primary-dark': 'primary-blue-dark', hover: 'hover-blue', background: 'background', surface: 'surface', outline: 'outline', 'primary-outline': 'primary-blue-80',
  correct: 'green', incorrect: 'red', warning: 'yellow', error: 'error', 'brand-accent': 'accent',
  ...Object.fromEntries(levels.map((l, i) => ['level-' + i, l.token])),
  ...Object.fromEntries(engagement.map((l, i) => ['engagement-' + i, l.token])),
};
const theme = Object.fromEntries(Object.entries(tokens).map(([name, token]) => [name, { token, fallback: color(token) }]));
const contract = { version: 1, source: 'alps-react-app/src', theme, performance: levels, engagement, icons, itemColors: ITEM_TYPE_FILL_COLOR, itemLabels: labels };
const js = '// Generated by tools/sync-alps-design-system.js from ALPS source. Do not edit by hand.\nwindow.INSIGHT_ALPS = ' + JSON.stringify(contract, null, 2) + ';\n';
const css = '/* Generated ALPS bridge. Host tokens are read, never redefined. */\n.insight-lens {\n' + Object.entries(theme).map(([name, t]) => '  --il-alps-' + name + ':var(--' + t.token + ',' + t.fallback + ');').join('\n') + '\n' + Object.entries(ITEM_TYPE_FILL_COLOR).map(([name, value]) => '  --il-item-' + name + ':' + value + ';').join('\n') + '\n}\n';
let stale = false;
for (const [file, content] of [['js/alps-design-system.js', js], ['css/alps-theme.css', css]]) {
  const target = path.join(root, file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) { console.error(file + ' differs from ALPS; run the sync command.'); stale = true; }
  } else fs.writeFileSync(target, content);
}
if (stale) process.exitCode = 1;
else console.log(process.argv.includes('--check') ? 'ALPS icons and theme match the source.' : 'Updated ALPS icons and theme.');
